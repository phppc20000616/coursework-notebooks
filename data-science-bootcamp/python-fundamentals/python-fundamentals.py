"""### 5-2: Define a function in Python.
In addition to the built-in functions and functions in the built-in modules, you can also create your own functions. These functions are called user-defined functions.

Here are some simple rules to define a function in Python.
*   Function blocks begin with the keyword `def` followed by the function name and parentheses.
*   Any input arguments should be placed within these parentheses. You can also define parameters inside these parentheses.
*   The code block within every function starts with a colon (`:`) and is indented
*   The statement `return [expression]` exits a function, optionally passing back an expression to the caller. A `return` statement with no arguments is the same as `return None`.

Basic function syntax:
```
def my_function(params):
  '''
  function briefs
  '''
  function_body
  return [expression]
```
Note that parameters / arguments have a positional behavior and you need to inform them in the same order that they were defined.

Once the function is defined, you can execute it by calling it from another function or directly from the Python prompt (CLI).
"""

def print_list(my_list):
  '''
  This string prints all the list elements passed to it.
  '''
  for x in my_list:
    print(x)
  return

cake_recipe = ["flour", 2, "butter", 1, "sugar", 0.5, "egg", 3]
print_list(cake_recipe)

# function with return value with type hints
def add(x, y):
  sum = x + y
  return sum

print(add(20, 30))

"""### 5-3. Python scope.
A variable created inside a functions belongs to the *local* scope of that function, and can only be used inside that function.

"""

def my_func():
  local_val = 5
  print(local_val)
  return

my_func()

print(local_val)    # You're expected to see a NameError complaining that 'local_val' isn't defined.

"""As explained in the example above, the variable `local_val` is not available outside the function, but it is available for any function inside the function:"""

def my_func():
  local_val = 10
  def my_inner_func():
    print(local_val)
  my_inner_func()
  return

my_func()

