"""## 5: Functions.
A Python function is a block of organized, reusable code that is used to perform a single, related action. Functions provide better modularity for your application and a high degree of code reusing.

A top-to-down approach towards building the processing logic involves defining blocks of independent reusable functions. A Python function may get invoked by any other function by passing required arguments. The called function returns its result back to the calling environment.

### 5-1: Python built-in functions.
Python's standard library includes a variety of built-in functions. The frequently used ones are `print()`, `int()`, `len()`, `sum()`, etc. These functions are always available, as they are loaded into computer's memory as soon as you start the Python interpreter.
"""

nums = [1, 2, 3, 4, 5]

