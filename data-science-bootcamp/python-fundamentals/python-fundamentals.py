"""###3-2: The match statement.
Python supports `match-case` statement, which can be also used as a part of decision making.
"""

def checkVowel(n):
  match n:
    case 'a': return "vowel alphabet"
    case 'e': return "vowel alphabet"
    case 'i': return "vowel alphabet"
    case 'o': return "vowel alphabet"
    case 'u': return "vowel alphabet"
    case _: return "simple alphabet"

print("letter a is a " + checkVowel('a'))
print("letter m is a " + checkVowel('m'))
print("letter o is a " + checkVowel('o'))

"""## 4: Loops or iteration statements.
Most of the processes require a series of instructions to be repeated executed. In programming terminology, it is called a loop.

If the control goes back unconditionally, it forms an infinite loop which is not desired as the rest of the code would *never* get executed.

In a conditional loop, the repeated iteration of block of statements goes on till a certain condition is met. Python supports a number of loops like *for* loop and *while* loop, as demonstrated in the following blocks.

### 4-1: The for loop.
"""

basket = ["apple", "peach", "watermelon"]
for x in basket:
  print(x)

"""### 4-2: The while loop."""

iter = 1
while iter < 6:
  print(iter)
  iter += 1

"""### 4-3: The break statement.

The *break* statement terminates the current loop and resumes execution at the next statement, and the most common use case is when some external condition is triggered requiring a hasty exit from a loop.

The break statement can be used in both for and while loops.

If you are using nested loops, the break statement stops the execution of the innermost loop and start executing the next line of the code after the block.
"""

for letter in "Python":
  if letter == 'h':
    break
  print("Current letter: ", letter)

var = 10
while var > 0:
  print("Value of var: ", var)
  var = var - 1
  if var == 5:
    break

print("Good bye!")

"""### 4-4: The continue statement.

The *continue* statement in Python returns the control to the beginning of the current loop. When encountered, the loop starts next iteration without executing the remaining statements in the current iteration.

The continue statement can be used in both for and while loops.
"""

for letter in "Python":
  if letter == "h":
    print("This is the continue block")
    continue
  print("Current letter: ", letter)
print("See you!")

# checking prime factors
num = 60
print("Checking prime factors for: ", num)

d = 2
while num > 1:
  if num % d == 0:
    print(d)
    num = num / d
    continue
  d = d + 1

"""### 4-5: The pass statement.

The *pass* statement is used when a statement is required syntactically but you do not want any command or code to execute.

The Python pass statement is a null operation, nothing happens when it executes. It can also be used as a placeholder (*i.e.*, in stubs) for your code where the details  have not yet been implemented.

"""

for letter in "Python":
  if letter == "h":
    pass
    print("This is the pass block")
  print("Current letter: ", letter)
print("Good bye!")

